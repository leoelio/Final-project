def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def rel(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def build_rows(args: argparse.Namespace) -> list[dict[str, str]]:
    rows = []
    for spec in SPECS:
        video = args.videos / spec["video"]
        metadata = read_json(video.with_suffix(".json"))
        summary = metadata["summary"]
        tcp_lift = summary.get("tcp_grasp_lift_success")
        result = f"success={summary['success']}, grasp_success={summary['grasp_success']}"
        if tcp_lift is not None:
            result += f", tcp_grasp_lift_success={tcp_lift}"
        rows.append(
            {
                "版本": spec["version"],
                "方法定位": spec["method"],
                "seed": str(metadata["seed"]),
                "结果": result,
                "目标距离": f"{float(summary['target_distance']):.4f}",
                "物体高度": f"{float(summary['object_z']):.4f}",
                "出界": str(summary["out_of_table"]),
                "视频文件": rel(video),
                "元数据文件": rel(video.with_suffix(".json")),
                "报告文件": spec["report"],
                "实验结论": spec["conclusion"],
                "论文边界": spec["boundary"],
                "完整viewer命令": spec["viewer"],
                "重新导出视频命令": spec["export"],
            }
        )
    return rows


def write_csv(path: Path, rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def md_row(values: list[str]) -> str:
    escaped = [value.replace("|", "\\|").replace("\n", " ") for value in values]
    return "| " + " | ".join(escaped) + " |"


def write_md(path: Path, rows: list[dict[str, str]]) -> None:
    lines = [
        "# 候选方法诊断视频索引",
        "",
        "版本：`candidate_diagnostic_video_index_v1`",
        "",
        "用途：集中记录 trajectory-conditioned BC / ACT / post-training 路线中的候选负例视频证据。它们用于解释为什么当前实现不能登记为可靠 ACT 或真实偏好后训练 baseline，量化结论仍以对应 CSV/JSON 评测为准。",
        "",
        "## 1. 视频明细",
        "",
        md_row(["版本", "方法定位", "seed", "结果", "目标距离", "物体高度", "视频文件", "论文边界"]),
        md_row(["---", "---", "---:", "---", "---:", "---:", "---", "---"]),
    ]
    for row in rows:
        lines.append(
            md_row(
                [
                    f"`{row['版本']}`",
                    row["方法定位"],
                    row["seed"],
                    row["结果"],
                    row["目标距离"],
                    row["物体高度"],
                    f"`{row['视频文件']}`",
                    row["论文边界"],
                ]
            )
        )

    lines.extend(["", "## 2. 完整可视化命令", ""])
    for row in rows:
        lines.extend([f"### {row['版本']}", "", "```powershell", row["完整viewer命令"], "```", ""])

    lines.extend(["## 3. 重新导出视频命令", ""])
    for row in rows:
        lines.extend([f"### {row['版本']}", "", "```powershell", row["重新导出视频命令"], "```", ""])

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    args = parse_args()
    rows = build_rows(args)
    write_csv(args.output_csv, rows)
    write_md(args.output_md, rows)
    print(f"candidate_video_md: {args.output_md}", flush=True)
    print(f"candidate_video_csv: {args.output_csv}", flush=True)
    print(f"candidate_video_rows: {len(rows)}", flush=True)


if __name__ == "__main__":
    main()
