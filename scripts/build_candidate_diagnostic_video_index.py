def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build a Chinese index for candidate diagnostic rollout videos.")
    parser.add_argument("--videos", type=Path, default=ROOT / "outputs" / "videos")
    parser.add_argument("--output-md", type=Path, default=ROOT / "docs" / "candidate_diagnostic_video_index.md")
    parser.add_argument("--output-csv", type=Path, default=ROOT / "docs" / "candidate_diagnostic_video_index.csv")
    return parser.parse_args()


def q(path: Path) -> str:
    return f'"{path}"'


def ps_command(script: str | Path, args: list[str | Path]) -> str:
    parts = ["&", q(PYTHON), q(ROOT / script)]
    for arg in args:
        parts.append(q(arg) if isinstance(arg, Path) else str(arg))
    return " ".join(parts)


def torch_ps_command(script: str | Path, args: list[str | Path]) -> str:
    return '$env:VLA_TORCH_PACKAGE_DIR="D:\\vla_torch_cuda_pkgs"\n' + ps_command(script, args)


